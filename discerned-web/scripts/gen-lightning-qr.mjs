// Regenerates public/support/lightning-qr.svg from LIGHTNING_ADDRESS in lib/support.ts.
//
// Run:  pnpm gen:qr
//
// The QR is a COMMITTED BUILD-TIME ASSET, not generated at runtime. The web app is a
// static export and the Lightning address is a constant, so a runtime QR dependency
// would add bundle weight and a package to keep patched in exchange for nothing.
// `qrcode` is fetched transiently by pnpm dlx and never enters package.json.
//
// Colours are baked in as literal black-on-white on purpose: QR scanners need dark
// modules on a light field, so the code must NOT follow the app's dark theme. See the
// .donate-qr comment in app/globals.css.

import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

// Install `qrcode` into a throwaway temp dir and import it from there. pnpm dlx puts the
// package in an isolated store that isn't on this script's resolution path, so a bare
// `import 'qrcode'` can't find it — and adding the dep to package.json is exactly what
// this script exists to avoid. The temp dir is removed on the way out.
const stage = join(tmpdir(), 'discerned-qrgen');
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
writeFileSync(join(stage, 'package.json'), JSON.stringify({ name: 'discerned-qrgen', private: true }), 'utf8');

console.log('Installing qrcode (temporary, not added to this project)…');
execFileSync('pnpm', ['add', '--silent', '--ignore-workspace', 'qrcode@1'], {
  cwd: stage, stdio: ['ignore', 'ignore', 'inherit'], shell: process.platform === 'win32',
});

const qrEntry = join(stage, 'node_modules', 'qrcode', 'lib', 'index.js');
const { toString: qrToString } = await import(pathToFileURL(qrEntry).href);

// Read the address from lib/support.ts rather than duplicating it — a second copy here
// would silently drift the moment someone edits one and not the other.
const supportSrc = readFileSync(resolve(root, 'lib/support.ts'), 'utf8');
const match = supportSrc.match(/export const LIGHTNING_ADDRESS = '([^']+)'/);
if (!match) {
  console.error('Could not find LIGHTNING_ADDRESS in lib/support.ts');
  process.exit(1);
}
const address = match[1];
// Encode the URI, not the bare address — that's what wallet scanners expect, and it
// makes the QR and the "Open in wallet" link carry an identical payload.
const uri = `lightning:${address}`;

const svg = await qrToString(uri, {
  type: 'svg',
  errorCorrectionLevel: 'M',
  margin: 2,
  color: { dark: '#000000', light: '#ffffff' },
});

const provenance = `<!-- Generated by scripts/gen-lightning-qr.mjs from ${uri} — do not edit by hand. Regenerate with \`pnpm gen:qr\`. -->\n`;
const outPath = resolve(root, 'public/support/lightning-qr.svg');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, provenance + svg, 'utf8');

rmSync(stage, { recursive: true, force: true });

console.log(`Wrote ${outPath}\n  payload: ${uri}`);
